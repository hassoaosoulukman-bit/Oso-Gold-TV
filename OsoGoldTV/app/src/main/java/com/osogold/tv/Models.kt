package com.osogold.tv

import java.util.Locale

/** One playable entry (TV channel, movie, series, radio station ...). */
data class Channel(
    val name: String,
    val url: String,
    val logo: String = "",
    val group: String = "",
    /** Not empty for an Xtream "series" entry: clicking it opens its episodes. */
    val seriesId: String = "",
    /** Xtream movie id (stream_id): used to load the story and the trailer of a movie. */
    val infoId: String = ""
)

/** A playlist added by the user (link or file copied into the app). [value] = URL or "file:<path>". */
data class CustomList(
    val id: String,
    val name: String,
    val value: String
)

/** A country shown in the "Countries" section. */
data class Country(
    val iso: String,
    val arab: Boolean
) {
    /** File code used by the iptv-org playlists (the UK is "uk", not "gb"). */
    val fileCode: String
        get() = if (iso.equals("GB", ignoreCase = true)) "uk" else iso.lowercase(Locale.ROOT)

    /** Flag emoji built from the two regional-indicator symbols of the ISO code. */
    val flag: String
        get() {
            val u = iso.uppercase(Locale.ROOT)
            if (u.length != 2) return "🏳"
            val first = Character.toChars(0x1F1E6 + (u[0] - 'A'))
            val second = Character.toChars(0x1F1E6 + (u[1] - 'A'))
            return String(first) + String(second)
        }

    /** Country name in Arabic (generated by the platform). */
    val nameAr: String
        get() {
            @Suppress("DEPRECATION")
            val name = Locale("", iso).getDisplayCountry(Locale("ar"))
            return if (name.isBlank()) iso else name
        }
}

/** One row of the list panel on the main screen. */
data class Row(
    val title: String,
    val subtitle: String = "",
    val leading: String = "",
    val channel: Channel? = null,
    val country: Country? = null,
    val isHeader: Boolean = false,
    /** Navigation marker: "sec:<id>", "pkg:<id>" or "back". */
    val tag: String = ""
)

/** The sections shown on the rotating orbit. */
enum class Section(
    val id: String,
    val labelRes: Int,
    val iconRes: Int,
    val sourceKey: String?
) {
    LIVE("live", R.string.sec_live, R.drawable.ic_live, DefaultData.SRC_LIVE),
    COUNTRIES("countries", R.string.sec_countries, R.drawable.ic_globe, null),
    MOVIES("movies", R.string.sec_movies, R.drawable.ic_film, DefaultData.SRC_MOVIES),
    SERIES("series", R.string.sec_series, R.drawable.ic_tv, DefaultData.SRC_SERIES),
    QURAN("quran", R.string.sec_quran, R.drawable.ic_quran, DefaultData.SRC_QURAN),
    RADIO("radio", R.string.sec_radio, R.drawable.ic_radio, DefaultData.SRC_RADIO),
    SUBS("subs", R.string.sec_subs, R.drawable.ic_server, null),
    SETTINGS("settings", R.string.sec_settings, R.drawable.ic_settings, null)
}
